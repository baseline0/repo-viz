"""Generate `just/generated.just`: endpoint recipes from typer commands, plus the shared base set.

Two sources feed the generated file:
- Endpoints: typer commands decorated with `@expose_api_secure`, found by reading the source with `ast` in the app's
  module and in the modules that hold its nested groups (`add_typer`). The module is never imported, so a command's
  import-time dependencies do not run during generation. Each endpoint becomes `<prefix>-<command-name>`, where the
  command name is the leaf name and must be unique across the repo; the recipe runs the full path (for example
  `reports deploy`). Its options are passed through as recipe parameters: a required option (`...`) is a parameter
  with no default, and an option with a literal str, int, or float default is a parameter with that default. Flags
  and None defaults are not parameters. The prefix is a
  command-line naming choice, not part of the endpoint: it comes from `just/recipes.toml` next to the generated file
  (`default_prefix`, optionally overridden per module in `[modules]`). A `[names]` table gives one command an
  exact recipe name, which is not prefixed.
  The decorator's arguments must be literals. A non-literal argument is refused, with the line that holds it.
  The app may be a `Typer(...)` assignment, or `app = <factory>()` where `<factory>` is a function in the same module
  that ends with `return Typer(...)`. The factory is read by `ast` and never called. Any other factory is refused.
- Base set: `BASE_RECIPES`, the same python- recipes emitted into every repo. Each has an ordered list of
  tools; the first one importable in the repo runs, and if none is present the recipe fails with a message.

Output is deterministic (sorted, no timestamps), so regenerating an unchanged CLI rewrites nothing and
`check_generated` detects a stale file by comparing content.

Regenerate with:
    uv run python -m repo_viz.autogen.cli generate-endpoints --module <pkg.cli> --app app --output just/generated.just
"""

from __future__ import annotations

import os
import subprocess
import tomllib
from collections.abc import Mapping
from pathlib import Path

from repo_viz.autogen.base_recipes import BASE_RECIPES, BaseRecipe, Tool, _render_base
from repo_viz.autogen.constants import REPO_ROOT, SUBPROCESS_TIMEOUT_SECONDS
from repo_viz.autogen.endpoint_discovery import EndpointRecipe, endpoint_recipes
from repo_viz.autogen.endpoint_render import _render_endpoint
from repo_viz.autogen.endpoint_source import read_exposed_arguments, resolve_module_file
from repo_viz.autogen.recipe_config import (
    EndpointRecipeError,
    RecipeConfig,
    load_recipe_config,
    recipes_config_path,
)

GENERATED_HEADER = "# AUTO-GENERATED by repo_viz.autogen.endpoint_recipes. DO NOT EDIT: regenerate instead."
REVISION_ENV = "FLEET_BASE_REVISION"
REVISION_PREFIX = "# repo-viz revision: "


def fleet_base_revision(environ: Mapping[str, str] | None = None) -> str:
    """The fleet-base commit this generator runs from, recorded in the generated header.

    `FLEET_BASE_REVISION` wins when set (the fleet-ops checker sets it when it runs the generator from an
    archive of a pinned revision). Otherwise the commit is read from the git checkout holding this package.
    Returns "unknown" when neither is available (for example an installed wheel with no git checkout).
    """
    override = (os.environ if environ is None else environ).get(REVISION_ENV)
    if override:
        return override
    try:
        result = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            timeout=SUBPROCESS_TIMEOUT_SECONDS,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return result.stdout.strip() or "unknown"


def console_invocation(module: str, app_name: str) -> str:
    """The command a recipe runs for `module:app_name`: the package's console script when one targets that app.

    The nearest pyproject.toml is read. A `[project.scripts]` entry whose target is `module:app_name` names the app
    as a command, so recipes run `uv run <script>`. Otherwise the recipe runs the module with `python -m`.
    """
    fallback = f"uv run python -m {module}"
    try:
        start = resolve_module_file(module).parent
    except EndpointRecipeError:
        return fallback
    for directory in (start, *start.parents):
        pyproject = directory / "pyproject.toml"
        if pyproject.exists():
            scripts = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project", {}).get("scripts", {})
            target = f"{module}:{app_name}"
            for name, spec in sorted(scripts.items()):
                if spec == target:
                    return f"uv run {name}"
            return fallback
    return fallback


def render_generated(module: str, app_name: str, config: RecipeConfig, include_base: bool = True) -> str:
    """Render the full generated justfile for `module:app_name`, read from source.

    `include_base=False` leaves out the base set. A file that is imported next to a repo's own generated file (the
    shared dispatch file) must not define the python- recipes a second time.

    Raises:
        EndpointRecipeError: If an endpoint recipe would collide with a base recipe or another endpoint.
    """
    endpoints = endpoint_recipes(module, app_name, config)
    bases = BASE_RECIPES if include_base else ()
    seen: dict[str, str] = {base.name: "base set" for base in bases}
    for recipe in endpoints:
        if recipe.name in seen:
            raise EndpointRecipeError(
                f"endpoint {recipe.command!r} would generate {recipe.name!r}, which the {seen[recipe.name]} "
                "already defines; rename the command, or change its prefix or [names] entry in just/recipes.toml"
            )
        seen[recipe.name] = f"endpoint {recipe.command!r}"

    sections = [
        GENERATED_HEADER,
        f"{REVISION_PREFIX}{fleet_base_revision()}",
        f"# Source: {module}:{app_name}",
        "# Base set first, then endpoints sorted by recipe name."
        if include_base
        else "# Endpoints sorted by recipe name.",
        "",
    ]
    sections.extend(_render_base(base) + "\n" for base in bases)
    invocation = console_invocation(module, app_name)
    sections.extend(_render_endpoint(recipe, invocation) + "\n" for recipe in endpoints)
    return "\n".join(sections)


def write_generated(path: Path, module: str, app_name: str, include_base: bool = True) -> bool:
    """Write the generated file if its content would change. Returns True if it was written.

    Raises:
        EndpointRecipeError: If the recipe config is missing or invalid, or the CLI cannot be turned into recipes.
    """
    config = load_recipe_config(recipes_config_path(path))
    content = render_generated(module, app_name, config, include_base)
    if path.exists() and path.read_text() == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return True


def without_revision_line(text: str) -> str:
    """Drop the `# fleet-base revision:` header line: it is checked against a pin by the caller, not by content."""
    return "".join(line for line in text.splitlines(keepends=True) if not line.startswith(REVISION_PREFIX))


def check_generated(path: Path, module: str, app_name: str, include_base: bool = True) -> str | None:
    """Return None if `path` matches what generation would produce, else a message saying why not.

    The revision header line is ignored here, since it names the commit that is checked out and would
    otherwise make every commit look stale. Compare it to the pin separately.
    """
    if not path.exists():
        return f"{path} is missing; run generate-endpoints"
    expected = render_generated(module, app_name, load_recipe_config(recipes_config_path(path)), include_base)
    if without_revision_line(path.read_text()) != without_revision_line(expected):
        return f"{path} is stale for {module}:{app_name}; run generate-endpoints"
    return None


